// Regenerates content/roadmaps/data/index.ts from the roadmap JSON files in that folder.
// Run after adding or removing a roadmap:  node scripts/gen-roadmap-index.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "content", "roadmaps", "data");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const name = (f) => "r_" + f.replace(/\.json$/, "").replace(/[^a-z0-9]/gi, "_");

const out = `// Generated by scripts/gen-roadmap-index.mjs. Do not edit by hand.
import { normalizeRoadmapDef } from "@/lib/roadmap";
${files.map((f) => `import ${name(f)} from "./${f}";`).join("\n")}

export const ROADMAP_DEFS = [
${files.map((f) => `  normalizeRoadmapDef(${name(f)}),`).join("\n")}
];
`;
fs.writeFileSync(path.join(dir, "index.ts"), out);

// Just the slugs, for proxy.ts (it answers unknown roadmap addresses with a real 404 without loading the content).
const slugs = files.map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")).slug);
fs.writeFileSync(path.join(dir, "..", "slugs.ts"), `// Generated by scripts/gen-roadmap-index.mjs. Do not edit by hand.
export const ROADMAP_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)};
`);
console.log(`Wrote index.ts and slugs.ts with ${files.length} roadmaps`);
